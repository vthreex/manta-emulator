"""Generate INVALID-observation grants for the original AVD/COMB HAL accessors.

For every callee of the platform-polling function (80501698..80502200) located in
the HAL block 80503000..80504700, find LBU/LHU/LW loads through the HAL context base
pointer in the AFEC/COMB aperture and emit one opaque-read rule per load. Each rule
is bound to the exact function code by SHA-256 (the loader re-verifies it). A rule
only lets the load return an INVALID observation: no value, mask, branch result or
write is supplied, and the first decision on the data still stops execution.
"""
import argparse, hashlib, struct, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from avd_register_ownership import mips_pointer_based, runtime_image, BASE  # noqa: E402

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--firmware', required=True)
p.add_argument('--base-policy', required=True, help='existing policy whose rules are kept')
p.add_argument('--out', required=True)
p.add_argument('--skip-address', action='append', default=[], help='addresses already modeled (hex)')
a = p.parse_args()

image = runtime_image(a.firmware)
words = struct.unpack('<%dI' % (len(image) // 4), image)
word = lambda pc: words[(pc - BASE) // 4]
calls = set()
for pc in range(0x80501698, 0x80502200, 4):
    w = word(pc)
    if w >> 26 == 3:
        t = (pc & 0xf0000000) | ((w & 0x3ffffff) << 2)
        if 0x80503000 <= t < 0x80504700:
            calls.add(t)


def fn_end(start):
    pc = start
    while pc < start + 0x400:
        if word(pc) == 0x03e00008:
            return pc + 8
        pc += 4
    raise SystemExit(f'no return found for {start:08x}')


skip = {int(x, 16) for x in a.skip_address}
loads = mips_pointer_based(image, 0x6A00, 0x6FFF)
base_text = Path(a.base_policy).read_text(encoding='utf-8').rstrip('\n')
existing = set()
for line in base_text.splitlines():
    if line.strip() and not line.lstrip().startswith('#'):
        f = line.split()
        existing.add((int(f[0], 0), int(f[1], 0), int(f[2], 0)))
lines, count = [], 0
for start in sorted(calls):
    end = fn_end(start)
    size = end - start
    digest = hashlib.sha256(image[start - BASE:end - BASE]).hexdigest()
    for virtual, pc, kind in loads:
        address = virtual & 0x1fffffff
        if kind != 'load' or not start <= pc < end or address in skip:
            continue
        w = word(pc)
        op, rt = w >> 26, (w >> 16) & 31
        width = {36: 1, 37: 2, 35: 4}.get(op)
        if not width or not rt:       # LB/LH (sign-extending) are not covered by the policy loader
            continue
        key = (pc, address, width)
        if key in existing:
            continue
        existing.add(key)
        lines.append(f'0x{pc:08x}\t0x{address:08x}\t{width}\t0x{start:08x}\t0x{size:x}\t{digest}')
        count += 1
header = ('\n\n# Generated by tools/gen_opaque_afec_policy.py: INVALID observations only for loads through the HAL context\n'
          '# base in the AFEC/COMB aperture, each bound to its function code hash. No value, mask, branch or write is supplied.\n')
Path(a.out).write_text(base_text + header + '\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print(f'{count} rules generated for {len(calls)} callees -> {a.out}')
