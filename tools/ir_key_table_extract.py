"""Extract the original firmware's raw IR byte -> application key code table.

Table: jump table at 0x8061773C, index = raw IR command byte (0..0xFC). Every target is a 4-instruction stub
  lui $s2,0x806C ; addiu $v0,$zero,CODE ; j 0x8046AA70 ; sb $v0,-0x6EF4($s2)      (stores CODE at 0x806B910C)
Targets of any other shape are reported as 'other' with their address; nothing is guessed.
"""
import struct, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from avd_register_ownership import runtime_image, BASE


def extract(firmware):
    image = runtime_image(firmware)
    words = struct.unpack('<%dI' % (len(image) // 4), image[:len(image) // 4 * 4])
    w = lambda a: words[(a - BASE) // 4]
    rows = []
    for raw in range(0xfd):
        t = w(0x8061773c + 4 * raw)
        i0, i1, i2, i3 = (w(t + 4 * j) for j in range(4))
        stub = i0 == 0x3c128 + 0x3c120000 - 0x3c120000 and False
        is_stub = (i0 >> 16 == 0x3c12 and (i0 & 0xffff) == 0x806c and i1 >> 16 == 0x2402 and i2 == 0x08000000 | (0x8046aa70 >> 2 & 0x3ffffff)
                   and i3 == 0xa2428000 + 0x10000 - 0x6ef4 + 0 - 0x8000 and True)
        # sb $v0,-0x6ef4($s2): opcode 0x28, rs=$s2(18), rt=$v0(2), imm=0x910c
        is_sb = i3 == (0x28 << 26 | 18 << 21 | 2 << 16 | 0x910c)
        is_lui = i0 == (0x0f << 26 | 18 << 16 | 0x806c)
        # the common tail is 8046AA70; the navigation-family stubs (app codes 7 and a few others) jump to 8046A984, which stores the 'arrow key' class and continues at 8046A754
        is_jump = i2 in (0x02 << 26 | (0x8046aa70 >> 2 & 0x3ffffff), 0x02 << 26 | (0x8046a984 >> 2 & 0x3ffffff))
        is_addiu = i1 >> 16 == 0x2402
        if is_lui and is_addiu and is_jump and is_sb:
            code = i1 & 0xffff
            if code >= 0x8000:
                code -= 0x10000
            rows.append((raw, code, t))
        else:
            rows.append((raw, None, t))
    return rows


if __name__ == '__main__':
    fw = sys.argv[1]
    out = Path(sys.argv[2])
    rows = extract(fw)
    lines = ['# Original firmware raw IR byte -> application key code (value stored at 0x806B910C).',
             '# Jump table 0x8061773C; every target is the stub  lui $s2,0x806C; addiu $v0,$zero,CODE; j 0x8046AA70; sb $v0,-0x6EF4($s2).',
             '# Generated by tools/ir_key_table_extract.py. app_code blank = target is not that stub (not decoded, not guessed). -1 = no key.',
             '# raw\tapp_code\ttarget']
    for raw, code, t in rows:
        lines.append('0x%02x\t%s\t0x%08x' % (raw, '' if code is None else (hex(code) if code >= 0 else str(code)), t))
    out.write_text('\n'.join(lines) + '\n')
    print(sum(1 for r in rows if r[1] is not None), 'decoded of', len(rows))
