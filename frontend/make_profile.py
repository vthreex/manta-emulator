"""Extracts the hardware/hypothesis argument list of a launcher .cmd into configs/frontend/profile-original.json.
The front end adds firmware, snapshot, native CPU, speed and presentation options on top of this list; it never edits the list itself.
usage: make_profile.py ../../work/launch-WINDOW-native.cmd"""
import json, shlex, sys
from pathlib import Path
line = [l for l in Path(sys.argv[1]).read_text().splitlines() if 'manta_native' in l and '--firmware' in l][0]
args = shlex.split(line.replace(chr(92), '/'), posix=True)[1:]
out, i = [], 0
drop_valued = {'--firmware', '--load-state', '--max-instructions', '--exploratory-video-plane', '--exploratory-cpi-after-load'}
drop_flags = {'--native-cpu', '--load-state-allow-extra-options', '--exploratory-gop-black-colorkey', '--exploratory-gop-black-colorkey-edge', '--exploratory-menu-no-autoexit'}
while i < len(args):
    a = args[i]
    if a in drop_valued:
        i += 2
        continue
    if a in drop_flags:
        i += 1
        continue
    out.append(a)
    i += 1
Path('configs/frontend/profile-original.json').write_text(json.dumps({
    'comment': 'hardware + labelled exploratory options of the stock-firmware desktop launcher (generated by frontend/make_profile.py)',
    'args': out}, indent=1))
print(len(out), 'arguments')
